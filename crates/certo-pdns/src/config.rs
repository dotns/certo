//! Settings for the supervised `pdns_server` and the generated `pdns.conf`.

use std::{
    net::SocketAddr,
    path::{Path, PathBuf},
    time::Duration,
};

use certo_core::config::Config;

use crate::PdnsError;

/// pdns `gsqlite3` schema, shipped with the pdns release the binary is built from.
pub const SCHEMA: &str = include_str!("../../../pdns/schema.sqlite3.sql");

/// Everything needed to run one `pdns_server`.
#[derive(Debug, Clone)]
pub struct PdnsConfig {
    /// `pdns_server` executable.
    pub binary: PathBuf,
    /// Directory holding `pdns.conf`, `pdns.sqlite3` and the control socket.
    pub dir: PathBuf,
    /// DNS listen address as configured for certo (`host:port` or `:port`).
    pub listen: String,
    /// Port of the API on 127.0.0.1.
    pub api_port: u16,
    /// SOA MNAME for new zones.
    pub nsname: String,
    /// SOA RNAME for new zones.
    pub nsadmin: String,
    /// certo log level name; mapped onto pdns `loglevel`.
    pub loglevel: String,
    /// Delay before the first restart after a crash (doubles up to 30 s).
    pub restart_backoff: Duration,
}

impl PdnsConfig {
    /// Derives the settings from the certo configuration; the binary defaults to
    /// `pdns_server` next to the running executable.
    pub fn from_config(config: &Config) -> Result<Self, PdnsError> {
        let binary = if config.pdns.binary.is_empty() {
            let exe = std::env::current_exe().map_err(PdnsError::io("locating the executable"))?;
            exe.with_file_name("pdns_server")
        } else {
            PathBuf::from(&config.pdns.binary)
        };
        let dir = if config.pdns.dir.is_empty() {
            PathBuf::from("data/pdns")
        } else {
            PathBuf::from(&config.pdns.dir)
        };
        let general = &config.general;
        let nsname = if general.nsname.is_empty() {
            general.domain.clone()
        } else {
            general.nsname.clone()
        };
        let nsadmin = if general.nsadmin.is_empty() {
            format!("hostmaster.{}", general.domain)
        } else {
            general.nsadmin.clone()
        };
        let cfg = Self {
            binary,
            dir,
            listen: general.listen.clone(),
            api_port: config.pdns.api_port,
            nsname,
            nsadmin,
            loglevel: config.logconfig.loglevel.clone(),
            restart_backoff: Duration::from_secs(1),
        };
        listen_lines(&cfg.listen)?;
        Ok(cfg)
    }

    /// Path of the pdns database.
    pub fn database(&self) -> PathBuf {
        self.dir.join("pdns.sqlite3")
    }

    /// Path of the generated configuration file.
    pub fn conf_path(&self) -> PathBuf {
        self.dir.join("pdns.conf")
    }

    /// Base URL of the API.
    pub fn api_url(&self) -> String {
        format!("http://127.0.0.1:{}", self.api_port)
    }

    /// Renders `pdns.conf`.
    pub fn render(&self, api_key: &str) -> Result<String, PdnsError> {
        let (address, port) = listen_lines(&self.listen)?;
        let dir = absolute(&self.dir).display().to_string();
        Ok(format!(
            "# Generated by certo on every start; edits are overwritten.\n\
             daemon=no\n\
             guardian=no\n\
             write-pid=no\n\
             setuid=\n\
             setgid=\n\
             disable-syslog=yes\n\
             log-timestamp=no\n\
             loglevel={loglevel}\n\
             log-dns-details=no\n\
             socket-dir={dir}\n\
             local-address={address}\n\
             local-port={port}\n\
             launch=gsqlite3\n\
             gsqlite3-database={dir}/pdns.sqlite3\n\
             gsqlite3-dnssec=yes\n\
             default-api-rectify=yes\n\
             default-soa-content={nsname} {nsadmin} 0 10800 3600 604800 3600\n\
             allow-axfr-ips=\n\
             security-poll-suffix=\n\
             api=yes\n\
             api-key={api_key}\n\
             webserver=yes\n\
             webserver-address=127.0.0.1\n\
             webserver-port={api_port}\n\
             webserver-allow-from=127.0.0.1\n\
             webserver-loglevel=none\n",
            loglevel = pdns_loglevel(&self.loglevel),
            nsname = self.nsname,
            nsadmin = self.nsadmin,
            api_port = self.api_port,
        ))
    }
}

fn absolute(path: &Path) -> PathBuf {
    if path.is_absolute() {
        path.to_path_buf()
    } else {
        std::env::current_dir().map_or_else(|_| path.to_path_buf(), |cwd| cwd.join(path))
    }
}

/// `local-address` and `local-port` for certo's `listen` value.
fn listen_lines(listen: &str) -> Result<(String, u16), PdnsError> {
    if let Some(port) = listen.strip_prefix(':') {
        let port = port
            .parse()
            .map_err(|_| PdnsError::Config(format!("invalid listen address {listen:?}")))?;
        return Ok(("0.0.0.0".to_owned(), port));
    }
    let addr: SocketAddr = listen
        .parse()
        .map_err(|_| PdnsError::Config(format!("invalid listen address {listen:?}")))?;
    Ok((addr.ip().to_string(), addr.port()))
}

/// pdns syslog-style levels: 3 error, 4 warning, 5 notice, 6 info, 7 debug.
fn pdns_loglevel(level: &str) -> u8 {
    match level.to_ascii_lowercase().as_str() {
        "error" => 3,
        "warn" | "warning" => 4,
        "debug" | "trace" => 7,
        _ => 5,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample() -> PdnsConfig {
        PdnsConfig {
            binary: "/opt/pdns_server".into(),
            dir: "/srv/data/pdns".into(),
            listen: "127.0.0.1:5300".into(),
            api_port: 8081,
            nsname: "ns1.example.com".into(),
            nsadmin: "hostmaster.example.com".into(),
            loglevel: "info".into(),
            restart_backoff: Duration::from_secs(1),
        }
    }

    #[test]
    fn renders_a_local_api_and_the_sqlite_backend() {
        let conf = sample().render("k3y").unwrap();
        for line in [
            "local-address=127.0.0.1",
            "local-port=5300",
            "gsqlite3-database=/srv/data/pdns/pdns.sqlite3",
            "api-key=k3y",
            "webserver-address=127.0.0.1",
            "webserver-port=8081",
            "default-soa-content=ns1.example.com hostmaster.example.com 0 10800 3600 604800 3600",
            "loglevel=5",
        ] {
            assert!(conf.lines().any(|l| l == line), "missing {line}\n{conf}");
        }
    }

    #[test]
    fn listen_forms() {
        assert_eq!(listen_lines(":53").unwrap(), ("0.0.0.0".to_owned(), 53));
        assert_eq!(listen_lines("[::1]:53").unwrap(), ("::1".to_owned(), 53));
        assert!(listen_lines("nonsense").is_err());
        assert!(listen_lines(":x").is_err());
    }

    #[test]
    fn loglevels() {
        assert_eq!(pdns_loglevel("error"), 3);
        assert_eq!(pdns_loglevel("warning"), 4);
        assert_eq!(pdns_loglevel("INFO"), 5);
        assert_eq!(pdns_loglevel("debug"), 7);
    }

    #[test]
    fn from_config_defaults_and_overrides() {
        let mut cfg = Config::default();
        cfg.general.listen = ":53".into();
        cfg.general.domain = "dns.example.com".into();
        cfg.pdns.api_port = 8081;
        let p = PdnsConfig::from_config(&cfg).unwrap();
        assert_eq!(p.binary.file_name().unwrap(), "pdns_server");
        assert_eq!(p.dir, PathBuf::from("data/pdns"));
        assert_eq!(p.nsname, "dns.example.com");
        assert_eq!(p.nsadmin, "hostmaster.dns.example.com");
        cfg.pdns.binary = "/usr/local/sbin/pdns_server".into();
        cfg.pdns.dir = "/var/lib/certo/pdns".into();
        cfg.general.listen = "bad".into();
        assert!(PdnsConfig::from_config(&cfg).is_err());
        cfg.general.listen = "0.0.0.0:53".into();
        let p = PdnsConfig::from_config(&cfg).unwrap();
        assert_eq!(p.binary, PathBuf::from("/usr/local/sbin/pdns_server"));
        assert_eq!(p.dir, PathBuf::from("/var/lib/certo/pdns"));
    }
}
