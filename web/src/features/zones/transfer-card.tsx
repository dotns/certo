import type { FormEvent } from 'react'
import type { Scope, TsigKey } from './api'
import { PlusIcon, Trash2Icon } from 'lucide-react'
import { useState } from 'react'
import { CodeBlock } from '@/shared/components/code-block'
import { ConfirmDialog } from '@/shared/components/confirm-dialog'
import { ErrorAlert } from '@/shared/components/error-alert'
import { FormDialog } from '@/shared/components/form-dialog'
import { Loading } from '@/shared/components/loading'
import { Button } from '@/shared/components/ui/button'
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/shared/components/ui/card'
import { Dialog, DialogContent, DialogDescription, DialogFooter, DialogHeader, DialogTitle } from '@/shared/components/ui/dialog'
import { Field, FieldDescription, FieldLabel } from '@/shared/components/ui/field'
import { Input } from '@/shared/components/ui/input'
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/shared/components/ui/select'
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from '@/shared/components/ui/table'
import { Textarea } from '@/shared/components/ui/textarea'
import { useAddTsigKeyMutation, useDeleteTsigKeyMutation, useSetTransferMutation, useTransferQuery } from './hooks'
import { parseAllowList, TSIG_ALGORITHMS } from './rrsets'

export function TransferCard({ scope, zone, nsTarget }: { scope: Scope, zone: string, nsTarget: string }) {
  const transfer = useTransferQuery(scope, zone, true)
  const save = useSetTransferMutation(scope, zone)
  const addKey = useAddTsigKeyMutation(scope, zone)
  const deleteKey = useDeleteTsigKeyMutation(scope, zone)
  const [allowFrom, setAllowFrom] = useState<string | null>(null)
  const [keyName, setKeyName] = useState('')
  const [algorithm, setAlgorithm] = useState<string>(TSIG_ALGORITHMS[0])
  const [created, setCreated] = useState<TsigKey | null>(null)
  const allowText = allowFrom ?? transfer.data?.allow_from.join('\n') ?? ''

  const submitAllow = (e: FormEvent) => {
    e.preventDefault()
    save.mutate(parseAllowList(allowText), { onSuccess: () => setAllowFrom(null) })
  }

  return (
    <Card>
      <CardHeader>
        <CardTitle>Zone transfer (AXFR)</CardTitle>
        <CardDescription>Secondaries may transfer the zone from the listed addresses or with a TSIG key.</CardDescription>
      </CardHeader>
      <CardContent className="flex flex-col gap-5">
        <ErrorAlert error={transfer.error ?? save.error ?? deleteKey.error} />
        {transfer.isPending && <Loading />}
        {transfer.data && (
          <>
            <form onSubmit={submitAllow} className="flex flex-col gap-2">
              <Field>
                <FieldLabel htmlFor="allow-from">Allowed source addresses</FieldLabel>
                <Textarea id="allow-from" rows={2} placeholder="192.0.2.53, 2001:db8::/64" value={allowText} onChange={e => setAllowFrom(e.target.value)} className="font-mono text-xs" />
                <FieldDescription>IP addresses or CIDR ranges, one per line. Empty denies unsigned transfers.</FieldDescription>
              </Field>
              <Button type="submit" variant="outline" size="sm" className="self-start" disabled={save.isPending || allowFrom === null}>Save addresses</Button>
            </form>
            <div className="flex flex-col gap-2">
              <div className="flex items-center justify-between gap-2">
                <span className="text-sm font-medium">TSIG keys</span>
                <FormDialog
                  trigger={(
                    <Button variant="outline" size="sm">
                      <PlusIcon data-icon="inline-start" />
                      Create key
                    </Button>
                  )}
                  title="Create TSIG key"
                  description="The secret is generated by the server and shown once."
                  submitLabel="Create"
                  onSubmit={async () => {
                    const key = await addKey.mutateAsync({ name: keyName.trim(), algorithm })
                    setCreated(key)
                  }}
                  onClose={() => setKeyName('')}
                >
                  <Field>
                    <FieldLabel htmlFor="tsig-name">Key name</FieldLabel>
                    <Input id="tsig-name" placeholder={`xfr.${zone}`} required autoFocus value={keyName} onChange={e => setKeyName(e.target.value)} />
                  </Field>
                  <Field>
                    <FieldLabel htmlFor="tsig-alg">Algorithm</FieldLabel>
                    <Select value={algorithm} onValueChange={v => setAlgorithm(String(v))}>
                      <SelectTrigger id="tsig-alg" className="w-44">
                        <SelectValue />
                      </SelectTrigger>
                      <SelectContent>
                        {TSIG_ALGORITHMS.map(a => <SelectItem key={a} value={a}>{a}</SelectItem>)}
                      </SelectContent>
                    </Select>
                  </Field>
                </FormDialog>
              </div>
              {transfer.data.tsig_keys.length === 0 && <p className="text-sm text-muted-foreground">No TSIG keys.</p>}
              {transfer.data.tsig_keys.length > 0 && (
                <Table>
                  <TableHeader>
                    <TableRow>
                      <TableHead>Name</TableHead>
                      <TableHead>Algorithm</TableHead>
                      <TableHead className="w-0"><span className="sr-only">Actions</span></TableHead>
                    </TableRow>
                  </TableHeader>
                  <TableBody>
                    {transfer.data.tsig_keys.map(k => (
                      <TableRow key={k.name}>
                        <TableCell className="font-mono text-xs">{k.name}</TableCell>
                        <TableCell>{k.algorithm}</TableCell>
                        <TableCell>
                          <ConfirmDialog
                            trigger={<Button variant="ghost" size="icon-sm" aria-label={`Delete TSIG key ${k.name}`}><Trash2Icon /></Button>}
                            title={`Delete TSIG key ${k.name}?`}
                            description="Secondaries signing with this key can no longer transfer the zone."
                            confirmLabel="Delete"
                            onConfirm={() => deleteKey.mutateAsync(k.name)}
                          />
                        </TableCell>
                      </TableRow>
                    ))}
                  </TableBody>
                </Table>
              )}
            </div>
          </>
        )}
      </CardContent>
      <Dialog open={created !== null} onOpenChange={open => !open && setCreated(null)}>
        <DialogContent>
          <DialogHeader>
            <DialogTitle>TSIG key created</DialogTitle>
            <DialogDescription>Copy the secret now; it is not shown again.</DialogDescription>
          </DialogHeader>
          {created?.secret && (
            <div className="flex flex-col gap-3">
              <CodeBlock title="Secret" code={created.secret} wrap />
              <CodeBlock title="Test transfer" code={`dig @${nsTarget} ${zone} AXFR -y ${created.algorithm}:${created.name}:${created.secret}`} wrap />
            </div>
          )}
          <DialogFooter showCloseButton />
        </DialogContent>
      </Dialog>
    </Card>
  )
}
